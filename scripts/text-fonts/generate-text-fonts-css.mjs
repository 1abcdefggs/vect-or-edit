// Generates src/renderer/css/text-fonts.css from the @fontsource-variable packages (the packages are the source of truth).
// Fontsource names each family "<Name> Variable"; the app and the saved settings use the plain name ("Source Serif 4"),
// so the generated rules keep the plain name. Font files are referenced through the package path and bundled by Vite.
// Usage: node scripts/text-fonts/generate-text-fonts-css.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUTPUT = path.join(root, 'src', 'renderer', 'css', 'text-fonts.css');

// One entry per family the app names. `sheets` are the package stylesheets that match what the app used from Google Fonts:
// italics only where they were loaded, and the optical-size axis for Source Serif 4.
export const TEXT_FONTS = [
  { pkg: '@fontsource-variable/source-serif-4', family: 'Source Serif 4', sheets: ['opsz.css', 'opsz-italic.css'] },
  { pkg: '@fontsource-variable/noto-serif-jp', family: 'Noto Serif JP', sheets: ['wght.css'] },
  { pkg: '@fontsource-variable/source-sans-3', family: 'Source Sans 3', sheets: ['wght.css', 'wght-italic.css'] },
  { pkg: '@fontsource-variable/noto-sans-jp', family: 'Noto Sans JP', sheets: ['wght.css'] },
  { pkg: '@fontsource-variable/source-code-pro', family: 'Source Code Pro', sheets: ['wght.css', 'wght-italic.css'] },
  { pkg: '@fontsource-variable/cascadia-code', family: 'Cascadia Code', sheets: ['wght.css'] }
];

function packageDir(pkg) {
  return path.dirname(require.resolve(`${pkg}/package.json`));
}

export function buildTextFontsCss() {
  const parts = [
    '/* Generated by scripts/text-fonts/generate-text-fonts-css.mjs from the @fontsource-variable packages. Do not edit by hand.',
    '   Text fonts are bundled so that text keeps its typeface offline. Licence: SIL OFL 1.1 (see THIRD_PARTY_NOTICES). */',
    ''
  ];
  for (const { pkg, family, sheets } of TEXT_FONTS) {
    const dir = packageDir(pkg);
    const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
    for (const sheet of sheets) {
      const css = fs.readFileSync(path.join(dir, sheet), 'utf8');
      const variableName = `'${family} Variable'`;
      if (!css.includes(`font-family: ${variableName};`)) throw new Error(`${pkg}/${sheet} does not declare ${variableName}`);
      parts.push(`/* ${pkg}@${version} ${sheet} */`);
      parts.push(css
        .replaceAll(`font-family: ${variableName};`, `font-family: '${family}';`)
        .replaceAll('url(./files/', `url(${pkg}/files/`)
        .trim(), '');
    }
  }
  return parts.join('\n').replace(/\r\n/g, '\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = buildTextFontsCss();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== css) {
      console.error('text-fonts.css is out of date; run node scripts/text-fonts/generate-text-fonts-css.mjs');
      process.exit(1);
    }
    console.log('text-fonts.css is up to date');
  } else {
    fs.writeFileSync(OUTPUT, css, 'utf8');
    console.log(`Wrote ${path.relative(root, OUTPUT)} (${(css.match(/@font-face/g) || []).length} @font-face rules)`);
  }
}
